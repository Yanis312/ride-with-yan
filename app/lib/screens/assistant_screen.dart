/// Assistant de bord : le passager pose ses questions (boutique, services,
/// idées à Ottawa et Gatineau) à un modèle de langage hébergé sur Azure.
class AssistantScreen extends StatefulWidget {
  const AssistantScreen({super.key, this.controller});

  /// Pour les tests ; sinon la conversation de la course en cours.
  final AssistantController? controller;

  @override
  State<AssistantScreen> createState() => _AssistantScreenState();
}

class _AssistantScreenState extends State<AssistantScreen> {
  late final AssistantController _assistant =
      widget.controller ?? AssistantController.instance;
  final _input = TextEditingController();
  final _scroll = ScrollController();

  @override
  void dispose() {
    _input.dispose();
    _scroll.dispose();
    super.dispose();
  }

  Future<void> _ask(String question) async {
    if (question.trim().isEmpty) return;
    _input.clear();
    final future = _assistant.ask(
      question,
      language: Localizations.localeOf(context).languageCode,
    );
    _scrollToEnd();
    await future;
    _scrollToEnd();
  }

  void _scrollToEnd() {
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (!_scroll.hasClients) return;
      _scroll.animateTo(
        _scroll.position.maxScrollExtent,
        duration: AppMotion.medium,
        curve: AppMotion.spring,
      );
    });
  }

  @override
  Widget build(BuildContext context) {
    final p = context.palette;
    return SectionScaffold(
      scene: Scene.profile,
      title: const Bi(
        'Yan, votre assistant',
        'Yan, your assistant',
      ).of(context),
      child: ListenableBuilder(
        listenable: _assistant,
        builder: (context, _) {
          final messages = _assistant.messages;
          final failure = _assistant.failure;
          return Column(
            crossAxisAlignment: CrossAxisAlignment.stretch,
            children: [
              Expanded(
                child: messages.isEmpty
                    ? _Welcome(onPick: _ask)
                    : ListView(
                        controller: _scroll,
                        padding: const EdgeInsets.only(bottom: 12),
                        children: [
                          for (final m in messages) _Bubble(message: m),
                          if (_assistant.waiting) const _Typing(),
                          if (failure != null)
                            Padding(
                              padding: const EdgeInsets.only(top: 8),
                              child: Text(
                                failureMessage(failure).of(context),
                                textAlign: TextAlign.center,
                                style: AppText.body(14, color: p.textMuted),
                              ),
                            ),
                        ],
                      ),
              ),
              const SizedBox(height: 12),
              _Composer(
                controller: _input,
                busy: _assistant.waiting,
                onSend: () => _ask(_input.text),
              ),
              const SizedBox(height: 6),
              Row(
                children: [
                  Expanded(
                    child: Text(
                      const Bi(
                        'Réponses générées par une IA (Azure, au Canada) : '
                            'elles peuvent se tromper. Vos questions ne sont '
                            'pas enregistrées.',
                        'Answers generated by AI (Azure, in Canada): they '
                            'can be wrong. Your questions are not stored.',
                      ).of(context),
                      style: AppText.body(11, color: p.textMuted),
                    ),
                  ),
                  const PrivacyLink(size: 11),
                ],
              ),
            ],
          );
        },
      ),
    );
  }
}

